def _snapshot(directory: Path) -> dict:
    return {str(p): p.read_bytes() for p in directory.rglob("*") if p.is_file()}


def test_apply_hard_link_creates_entry_and_transaction(monkeypatch, home, ollama_blob):
    ollama = _FakeOllama()
    ollama.add_model("qwen2.5:7b-instruct", blob_path=str(ollama_blob))
    ollama.install(monkeypatch)
    source_bytes = ollama_blob.read_bytes()

    plan = adopt._build_plan(_args(model="qwen2.5:7b-instruct"))
    report = adopt._apply(_args(model="qwen2.5:7b-instruct"), plan)

    assert report["status"] == "adopted"
    target = Path(report["clozn_path"])
    assert target.is_file()
    assert target.read_bytes() == source_bytes
    assert os.stat(target).st_nlink >= 2          # shares the inode with ollama_blob

    tx_path = Path(report["transaction_path"])
    document = json.loads(tx_path.read_text(encoding="utf-8"))
    from clozn import schemas
    schemas.validate(document, "clozn.adopt-ollama.v1")
    assert document["clozn"]["mode"] == "hard_link"
    assert document["ollama"]["model_name"] == "qwen2.5:7b-instruct"

    # source untouched
    assert ollama_blob.read_bytes() == source_bytes


