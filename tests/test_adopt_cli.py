"""Model-free, fixture-driven tests for `clozn adopt ollama` (clozn.cli.commands.adopt).

No real Ollama process and no real network are ever used: `urllib.request.urlopen` is monkeypatched to
answer a small in-memory fake registry (see _FakeOllama), and "Ollama's blob" is a real temp file on
disk holding a hand-built synthetic GGUF (same technique tests/test_fit_planner.py uses for
parse_gguf_header -- duplicated here in miniature so this file stays self-contained).

These tests are also the binding-condition proof the coordinator required:
  * test_undo_restores_source_untouched_and_byte_identical  -- undo actually restores prior state, not
    just a docstring claim.
  * test_undo_refuses_when_ollama_side_reference_is_gone     -- the GC case refuses cleanly and leaves
    Clozn's own copy in place; it never silently succeeds.
  * test_apply_never_writes_under_the_fake_ollama_directory  -- adoption never writes into "Ollama"
    storage, proven by snapshotting that whole directory tree before and after.
"""
