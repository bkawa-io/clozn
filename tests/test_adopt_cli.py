def test_undo_restores_source_untouched_and_byte_identical(monkeypatch, home, ollama_blob):
    """The binding condition: undo must actually restore prior state, proven by assertion, not asserted
    only in a docstring."""
    ollama = _FakeOllama()
    ollama.add_model("qwen2.5:7b-instruct", blob_path=str(ollama_blob))
    ollama.install(monkeypatch)
    source_bytes_before = ollama_blob.read_bytes()
    ollama_dir_before = _snapshot(ollama_blob.parent)

    plan = adopt._build_plan(_args(model="qwen2.5:7b-instruct"))
    applied = adopt._apply(_args(model="qwen2.5:7b-instruct"), plan)
    target = Path(applied["clozn_path"])
    tx_path = Path(applied["transaction_path"])
    assert target.is_file() and tx_path.is_file()

    undone = adopt._undo(_args(model="qwen2.5:7b-instruct"))

    assert undone["status"] == "undone"
    assert not target.exists()
    assert not tx_path.exists()
    # prior state (the Ollama-side source) is exactly as it was, byte for byte
    assert ollama_blob.read_bytes() == source_bytes_before
    assert _snapshot(ollama_blob.parent) == ollama_dir_before


def test_undo_refuses_when_ollama_side_reference_is_gone(monkeypatch, home, ollama_blob):
    """The GC case: refuse cleanly, never silently succeed."""
    ollama = _FakeOllama()
    ollama.add_model("qwen2.5:7b-instruct", blob_path=str(ollama_blob))
    ollama.install(monkeypatch)

    plan = adopt._build_plan(_args(model="qwen2.5:7b-instruct"))
    applied = adopt._apply(_args(model="qwen2.5:7b-instruct"), plan)
    target = Path(applied["clozn_path"])

    # Simulate Ollama removing/GC'ing its own reference to the shared inode.
    ollama_blob.unlink()
    assert os.stat(target).st_nlink == 1

    with pytest.raises(ValueError, match="only one remaining hard link"):
        adopt._undo(_args(model="qwen2.5:7b-instruct"))

    # Undo must NOT have deleted Clozn's own copy -- it is now the last copy of this model's weights.
    assert target.is_file()


